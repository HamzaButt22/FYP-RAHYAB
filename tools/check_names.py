"""The app's copy of the common-names list must match the API's (the full-name nickname rule, FR-102).

The master is backend/api/src/rahyaab_api/data/common_names.json. The app copy,
frontend/mobile/src/join/commonNames.ts, is generated from it:

    python tools/check_names.py --write    regenerate the app copy after editing the JSON
    python tools/check_names.py            fail (exit 1) if the copy is out of date (CI)
"""

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MASTER = ROOT / "backend/api/src/rahyaab_api/data/common_names.json"
COPY = ROOT / "frontend/mobile/src/join/commonNames.ts"


def render() -> str:
    data = json.loads(MASTER.read_text(encoding="utf-8"))
    names = data["first_names"] + data["surnames"]
    lines = [
        "// Generated by tools/check_names.py from backend/api/src/rahyaab_api/data/common_names.json.",
        "// Do not edit by hand: edit the JSON, then run `python tools/check_names.py --write`.",
        "",
        "export const COMMON_NAMES: readonly string[] = [",
        *(f"  {json.dumps(n, ensure_ascii=False)}," for n in names),
        "];",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    expected = render()
    if "--write" in sys.argv:
        COPY.write_text(expected, encoding="utf-8", newline="\n")
        print(f"wrote {COPY.relative_to(ROOT)}")
        return 0
    actual = COPY.read_text(encoding="utf-8") if COPY.exists() else ""
    if actual != expected:
        print(f"{COPY.relative_to(ROOT)} is out of date: run python tools/check_names.py --write")
        return 1
    print("common names in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
