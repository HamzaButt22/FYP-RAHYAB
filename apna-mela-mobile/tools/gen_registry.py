import os, sys
root = sys.argv[1]  # project root
base = os.path.join(root, "assets", "game")
lines = ["// AUTO-GENERATED by tools/gen_registry.py - static requires so Metro bundles every asset.", "/* eslint-disable */", "",
         "export const IMAGES: Record<string, number> = {"]
for d, _, fs in sorted(os.walk(os.path.join(base, "images"))):
    for f in sorted(fs):
        if f.endswith(".webp"):
            rel = os.path.relpath(os.path.join(d, f), os.path.join(base, "images"))
            key = rel[:-5].replace(os.sep, "/")
            lines.append(f'  "{key}": require("../../assets/game/images/{rel}"),')
lines += ["};", "", "export const AUDIO: Record<string, number> = {"]
for kind in ("music", "sfx"):
    for f in sorted(os.listdir(os.path.join(base, "audio", kind))):
        lines.append(f'  "{f[:-4]}": require("../../assets/game/audio/{kind}/{f}"),')
lines += ["};", ""]
os.makedirs(os.path.join(root, "src", "assets"), exist_ok=True)
open(os.path.join(root, "src", "assets", "registry.ts"), "w").write("\n".join(lines))
print(len(lines))
